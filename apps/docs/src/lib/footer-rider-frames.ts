// Footer rider frames: a racehorse and jockey as dot grids, for a small race along the footer
// line: walk in, set at the start, race, cross the finish, ease up and walk off.
//
// Sources (all public domain, from Wikimedia Commons):
// - Gallop: Eadweard Muybridge, "The Horse in Motion" (1878), from the cut-out animation
//   "Muybridge race horse ~ big transp.gif". 15 frames, one stride.
// - Walk: Muybridge, "Descriptive Zoopraxography" (1893), plate 46 walk cycle line drawings,
//   "Descriptive Zoopraxography 046 walkcycle.gif". 10 frames, one stride. The outlines were
//   filled in and scaled to the gallop horse's body depth, and a rider was added: jockeys sit
//   up at a walk and crouch to race.
// Every frame was sampled onto the same 21-row dot grid, bottom row on the ground. The
// arm-up frames add a short raised arm to the rider, for the celebration after the finish.
//
// Key: '#' solid dot, '=' edge dot (lighter), '+' lightest dot (rider's trousers, far legs),
// '.' empty.

// How far a planted hoof moves back between frames, in dots. Moving the sprite forward by
// this much each frame keeps hooves on the ground still, so the horse does not slide.
