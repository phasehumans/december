#!/usr/bin/env bun
// Builds the docs page list that the search modal shows. Runs from build.ts and
// can run by hand: `bun run scripts/gen-docs-index.ts` from apps/web.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs'
import path from 'path'

import { format, resolveConfig } from 'prettier'

const webDir = path.resolve(import.meta.dir, '..')
const docsDir = path.resolve(webDir, '../docs/src/pages/docs')
const outFile = path.join(webDir, 'src/features/navigation/search/docsIndex.generated.ts')

type DocsEntry = { slug: string; title: string; keywords: string[] }

const frontmatterValue = (source: string, key: string) => {
    const match = source.match(new RegExp(`^${key}:\\s*['"]?(.+?)['"]?\\s*$`, 'm'))
    return match ? match[1].trim() : null
}

const buildDocsIndex = (dir: string): DocsEntry[] => {
    return readdirSync(dir)
        .filter((file) => file.endsWith('.mdx') || file.endsWith('.md'))
        .map((file) => {
            const source = readFileSync(path.join(dir, file), 'utf8')
            const base = file.replace(/\.mdx?$/, '')
            const slug = base === 'index' ? '' : base
            const title = frontmatterValue(source, 'title') ?? base
            const description = frontmatterValue(source, 'description')
            const headings = [...source.matchAll(/^#{2,3}\s+(.+)$/gm)].map((m) =>
                m[1].replace(/^\d+\.\s*/, '').trim()
            )
            const keywords = [description, ...headings]
                .filter((k): k is string => Boolean(k))
                .map((k) => k.toLowerCase())
            return { slug, title, keywords: [...new Set(keywords)] }
        })
        .sort((a, b) => a.title.localeCompare(b.title))
}

export const writeDocsIndex = async () => {
    if (!existsSync(docsDir)) {
        console.log('docs index: apps/docs not found, keeping the committed index')
        return
    }
    const entries = buildDocsIndex(docsDir)
    const body =
        '// Generated by apps/web/scripts/gen-docs-index.ts. Do not edit by hand.\n' +
        'type DocsIndexEntry = { slug: string; title: string; keywords: string[] }\n\n' +
        `export const DOCS_INDEX: DocsIndexEntry[] = ${JSON.stringify(entries, null, 4)}\n`
    const config = (await resolveConfig(outFile)) ?? {}
    writeFileSync(outFile, await format(body, { ...config, filepath: outFile }))
    console.log(`docs index: ${entries.length} pages`)
}

if (import.meta.main) await writeDocsIndex()
